"""用户文本脱敏：把结构化个人标识替换成占位符，再送外部模型。

为什么要有这一层：工单原话会原样发给第三方模型（DeepSeek / OpenAI 等）。
用户自报的手机号、身份证号、银行卡号、邮箱一旦进了外部 API，就脱离了本地
可控范围——日志、缓存、训练数据都可能留下副本。判定链本身不需要这些数字
（规则引擎只看订单事实与意图枚举），所以发出去之前替换掉，判定不受影响。

**这一层能做什么、不能做什么，要分清**：

- 能可靠识别的是**结构化标识**：11 位手机号、18 位身份证号、16–19 位银行卡号、
  邮箱地址。它们有固定格式，正则误伤率低。
- **地址只做到"像地址"**：省/市/区/县 + 路/街/号/栋/室 这种形态能认出来，
  但口语化说法（"我家在 XX 路 3 号"缺省市区）认不全——这是启发式，不是保证。
- **认不出的**：姓名、非成句的地址片段。这些没有稳定格式，正则硬套会大面积
  误伤正文。所以本模块**不假装**覆盖了它们——真实工单接入前，要么在采集端
  就不收，要么换 NER 模型，不能只靠这里的正则。
- 替换用 `<PHONE>`、`<ID>` 这类占位符而不是删除：保留"这里有个号码"的语义，
  模型仍能理解"我手机号是 XXX，帮我改地址"，关键词降级路径也不受影响。
  占位符与 `tools/import_public_cases.py` 导入公开语料时的口径一致——离线导入
  和在线送模型共用这里的规则，不会出现两套标准。

零依赖、纯函数、确定性——同样的输入永远得到同样的输出，便于单测与回放。
"""

from __future__ import annotations

import re

# 顺序有意义：先长后短。18 位身份证里可能包含 11 位手机号片段，
# 但各模式都带数字边界（前后不能再接数字），长串内的片段匹配不到，
# 这里保持"长格式优先"只是为了计数标注更准确。
_RULES: tuple[tuple[str, re.Pattern[str]], ...] = (
    # 18 位身份证：17 位数字 + 校验位（数字或 X）
    ("ID", re.compile(r"(?<![0-9A-Za-z])\d{17}[\dXx](?![0-9A-Za-z])")),
    # 银行卡：16–19 位连续数字
    ("BANK", re.compile(r"(?<!\d)\d{16,19}(?!\d)")),
    # 手机号：11 位，1 开头，第二位 3–9
    ("PHONE", re.compile(r"(?<!\d)1[3-9]\d{9}(?!\d)")),
    # 邮箱
    ("EMAIL", re.compile(r"\b[\w.+-]+@[\w-]+\.[\w.-]+\b")),
    # 详细地址：省/市/区/县 + 路/街/道 + 门牌（号/栋/楼/室/单元），命中才替换。
    # 冒号后的门牌只允许地址字符（数字、空格、号栋楼室单元层），不允许任意汉字——
    # 否则"幸福路小区门口等我"这类会把正常正文一起吞掉，意图识别就少了一块。
    ("ADDR", re.compile(
        r"[一-龥]{2,}(?:省|市|自治区)[一-龥]{0,10}(?:市|区|县)"
        r"[一-龥A-Za-z0-9\-]{0,20}(?:路|街|道)"
        r"[0-9零一二三四五六七八九十百A-Za-z\s\-号栋楼室单元层]{0,20}"
    )),
)


PLACEHOLDERS: tuple[str, ...] = tuple(f"<{label}>" for label, _ in _RULES)


def redact(text: str) -> tuple[str, dict[str, int]]:
    """脱敏。返回 (替换后的文本, 各类型命中次数)。

    命中次数用于让调用方把"这次送出去的内容做过脱敏"记进 trace，
    而不是让脱敏变成一件没人知道做没做的隐形操作。
    """
    hits: dict[str, int] = {}
    out = text
    for label, pattern in _RULES:
        out, n = pattern.subn(f"<{label}>", out)
        if n:
            hits[label] = n
    return out, hits


def redact_text(text: str) -> str:
    """只要结果、不要计数的简写。"""
    return redact(text)[0]


if __name__ == "__main__":
    samples = [
        "我手机号 13812345678，昨天买的鞋子开线了",
        "身份证 11010519491231002X，订单要改地址",
        "卡号 6222021234567890123 退这里",
        "邮箱 zhang.san+shop@example.com 联系我",
        "订单 ORD10001 已经签收 3 天，想退",
        "地址：北京市朝阳区建国路 88 号 3 栋 502 室",
        "订单号 1381234567890123 不是身份证也不是卡号",
    ]
    for s in samples:
        cleaned, hits = redact(s)
        print(f"原文: {s}")
        print(f"脱敏: {cleaned}")
        print(f"命中: {hits or '无'}\n")
